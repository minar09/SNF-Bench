#!/usr/bin/env python3
"""Data for the journal's scene figure and interactive companions, from scene specifications only.

Writes, never reading scores or videos:

* JOURNAL_TCSVT/figures/generated/scene_donut.tex: TikZ segments of the
  scene-composition donut (inner ring: medium family, outer ring: transport
  regime), drawn by sec/fig_scenes.tex;
* JOURNAL_TCSVT/interactive/assets/scenes.js: every T2V and I2V scene
  specification, read by interactive/scene_explorer.html.

The family grouping (water, atmosphere, heat and combustion) is for display;
results are macro-averaged over regimes. Directions are text-derived
candidate labels, not verified annotations. No source image is exported:
only 2 of 48 I2V sources have a recorded licence.

    /home/minar/miniconda3/envs/snfeval/bin/python scripts/build_journal_visuals.py
"""
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GEN = ROOT / 'JOURNAL_TCSVT' / 'figures' / 'generated'
ASSETS = ROOT / 'JOURNAL_TCSVT' / 'interactive' / 'assets'
FAMILIES = [('Water', 'famWater', ['channel_flow', 'falling_water', 'oscillatory_water', 'accumulating_level']),
            ('Atmosphere', 'famAir', ['falling_precip', 'windborne']),
            ('Heat \\& combustion', 'famHeat', ['combustion', 'buoyant_plume', 'geothermal'])]
LABEL = {'channel_flow': 'Channel flow', 'falling_water': 'Falling water',
         'oscillatory_water': 'Oscillatory water', 'accumulating_level': 'Accumulating level',
         'falling_precip': 'Precipitation', 'buoyant_plume': 'Buoyant plume',
         'combustion': 'Combustion', 'windborne': 'Windborne', 'geothermal': 'Geothermal'}
R_IN, R_MID, R_OUT = 0.95, 1.55, 2.35   # cm


def seg(a0, a1, r0, r1, colour, shade):
    return (f'\\fill[{colour}!{shade},draw=white,line width=.8pt] ({a0:.2f}:{r0}) arc ({a0:.2f}:{a1:.2f}:{r0}) '
            f'-- ({a1:.2f}:{r1}) arc ({a1:.2f}:{a0:.2f}:{r1}) -- cycle;')


def donut(t2v, i2v):
    lines = ['% generated by scripts/build_journal_visuals.py; do not edit']
    a = 90.0
    total = t2v['n']
    for fam, colour, regimes in FAMILIES:
        fam_n = sum(t2v['counts'][k] for k in regimes)
        f0 = a
        for j, k in enumerate(regimes):
            span = 360.0 * t2v['counts'][k] / total
            a1 = a - span
            lines.append(seg(a1, a, R_MID, R_OUT, colour, 75 - 15 * j))
            mid = math.radians((a + a1) / 2)
            lx, ly = (R_OUT + 0.18) * math.cos(mid), (R_OUT + 0.18) * math.sin(mid)
            anchor = 'west' if lx > 0.15 else ('east' if lx < -0.15 else ('south' if ly > 0 else 'north'))
            lines.append(f'\\node[anchor={anchor},font=\\scriptsize,inner sep=1pt,align=left] at ({lx:.2f},{ly:.2f}) '
                         f'{{{LABEL[k]}\\\\[-1pt]\\textcolor{{snfgrey}}{{{t2v["counts"][k]}\\,/\\,{i2v["counts"][k]}}}}};')
            a = a1
        lines.append(seg(a, f0, R_IN, R_MID - 0.05, colour, 100))
        mid = math.radians((a + f0) / 2)
        r = (R_IN + R_MID) / 2
        pct = 100.0 * fam_n / total
        lines.append(f'\\node[font=\\tiny\\bfseries,text=white,align=center] at ({r * math.cos(mid):.2f},'
                     f'{r * math.sin(mid):.2f}) {{{pct:.0f}\\%}};')
    lines.append(f'\\node[align=center,font=\\scriptsize] at (0,0) {{\\textbf{{{t2v["n"]}}} T2V\\\\'
                 f'\\textbf{{{i2v["n"]}}} I2V}};')
    return '\n'.join(lines) + '\n'


def main():
    GEN.mkdir(parents=True, exist_ok=True)
    ASSETS.mkdir(parents=True, exist_ok=True)
    t2v = json.loads((ROOT / 'manifest/prompts_v2.json').read_text())
    i2v = json.loads((ROOT / 'manifest/i2v_pairs_v2.json').read_text())
    for k in LABEL:
        assert t2v['counts'][k] == 2 * i2v['counts'][k], k   # the donut's single ring relies on this
    (GEN / 'scene_donut.tex').write_text(donut(t2v, i2v))
    rows = []
    for track, doc, key in [('T2V', t2v, 'scenes'), ('I2V', i2v, 'pairs')]:
        for s in doc[key]:
            rows.append(dict(track=track, id=s['id'], category=s['category'], direction=s.get('direction'),
                             text=s['text'], licence=s.get('licence') if track == 'I2V' else None))
    meta = dict(families=[dict(name=f.replace('\\&', '&'), regimes=r) for f, _, r in FAMILIES], labels=LABEL,
                direction_scorable=dict(T2V=t2v.get('direction_scorable'),
                                        I2V=sum(1 for p in i2v['pairs'] if p.get('direction'))))
    (ASSETS / 'scenes.js').write_text('window.SCENES = ' + json.dumps(dict(meta=meta, rows=rows)) + ';\n')
    print(GEN / 'scene_donut.tex', len(rows), 'scene rows')


if __name__ == '__main__':
    main()
