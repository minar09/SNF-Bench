#!/usr/bin/env python3
"""CSV data for the pgfplots figures of the TCSVT draft (JOURNAL_TCSVT/figures/data/).

Every value is read from a saved development report; nothing is recomputed. Each
CSV is written with a header comment naming its source report and its SHA-256.

* known_answer_replay.csv: cand-replay-signature-0 late-half suspect rates per
  control mode (manifest/realism_dev_2026_11_05/replay_signature_scenetether.json).
* known_answer_paste.csv: per-scene source-match proxy pi of A2 for the
  pass-throughs and each composite construction (support_provenance_v1_*.json),
  with a deterministic vertical jitter for the strip plot.

    /home/minar/miniconda3/envs/snfeval/bin/python scripts/build_journal_plots.py
"""
import hashlib
import json
import os

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEV = os.path.join(ROOT, "manifest/realism_dev_2026_11_05")
OUT = os.path.join(ROOT, "JOURNAL_TCSVT/figures/data")
MODE_LABEL = {"passthrough_crf18": "unmodified", "loop_exact": "exact loop", "loop_xfade": "cross-faded loop",
              "pingpong": "ping-pong", "freeze": "freeze", "reverse_tail": "reversed tail", "shuffle": "shuffle",
              "speed2": "speed x2", "speed05": "speed x0.5", "noise_warp": "noise warp"}


def header(path, src):
    rel = os.path.relpath(src, ROOT)
    return f"# generated by scripts/build_journal_plots.py from {rel} sha256={hashlib.sha256(open(src, 'rb').read()).hexdigest()[:16]}\n"


def replay():
    src = f"{DEV}/replay_signature_scenetether.json"
    s = json.load(open(src))["summary"]
    lines = ["y,label,n,replay,pingpong,freeze"]
    for i, (md, lab) in enumerate(reversed(list(MODE_LABEL.items()))):
        v = s[md]
        lines.append(f"{i},{lab},{v['n']},{v['late_replay_suspect_rate']:.4f},"
                     f"{v['late_pingpong_suspect_rate']:.4f},{v['late_freeze_suspect_rate']:.4f}")
    open(f"{OUT}/known_answer_replay.csv", "w").write(header(path=None, src=src) + "\n".join(lines) + "\n")


def paste():
    groups = [("default", "passthrough_crf18", "unmodified"), ("fp", "passthrough_crf18", "unmodified"),
              ("unt", "passthrough_crf18", "unmodified"), ("default", "control_pasteback", "hard paste"),
              ("fp", "control_composite", "feathered composite"), ("unt", "control_composite", "untethered composite"),
              ("default", "control_still", "source still")]
    order = ["source still", "untethered composite", "feathered composite", "hard paste", "unmodified"]
    rng = np.random.default_rng(0)
    rows, heads, med = ["y,label,pi"], set(), {}
    for cell, md, lab in groups:
        src = f"{DEV}/support_provenance_v1_{cell}.json"
        heads.add(header(None, src))
        for r in json.load(open(src))["rows"]:
            x = r.get("controls", {}).get(md, {}).get("pi_proxy")
            if x is None:
                continue
            y = order.index(lab) + rng.uniform(-0.28, 0.28)
            rows.append(f"{y:.3f},{lab},{x:.4f}")
            med.setdefault(lab, []).append(x)
    open(f"{OUT}/known_answer_paste.csv", "w").write("".join(sorted(heads)) + "\n".join(rows) + "\n")
    open(f"{OUT}/known_answer_paste_median.csv", "w").write(
        "y,label,n,median\n" + "\n".join(f"{order.index(k)},{k},{len(v)},{np.median(v):.4f}" for k, v in med.items()) + "\n")


def main():
    os.makedirs(OUT, exist_ok=True)
    replay()
    paste()
    print("wrote", sorted(os.listdir(OUT)))


if __name__ == "__main__":
    main()
